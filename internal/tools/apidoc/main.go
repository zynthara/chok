// Command apidoc writes docs/api.md, the map of chok v3's public API: for
// each public package, every line `go doc -short` prints for it — the
// lines hack/apibudget.sh counts against hack/budget.txt — with the first
// sentence of its comment. Run it from the repository root:
//
//	go run ./internal/tools/apidoc          # rewrite docs/api.md
//	go run ./internal/tools/apidoc -check   # fail if docs/api.md is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

const module = "github.com/zynthara/chok/v3"

// apiDoc is docs/api.md, relative to the repository root.
const apiDoc = "docs/api.md"

func main() {
	check := flag.Bool("check", false, "fail if "+apiDoc+" is not current, writing nothing")
	flag.Parse()
	want, err := render(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "apidoc:", err)
		os.Exit(1)
	}
	have, _ := os.ReadFile(apiDoc)
	switch {
	case bytes.Equal(have, want):
		fmt.Println(apiDoc, "is current")
	case *check:
		fmt.Fprintf(os.Stderr, "apidoc: %s is not current; run go run ./internal/tools/apidoc\n", apiDoc)
		os.Exit(1)
	default:
		if err := os.WriteFile(apiDoc, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "apidoc:", err)
			os.Exit(1)
		}
		fmt.Println(apiDoc, "written")
	}
}

// pkg is one public package in budget.txt's order.
type pkg struct {
	rel      string // chok, db, store/where, identity/google, ...
	provider bool
}

// packages reads the public packages from hack/budget.txt, which lists
// every one of them (the budget fails on an unlisted package).
func packages(root string) ([]pkg, error) {
	data, err := os.ReadFile(filepath.Join(root, "hack", "budget.txt"))
	if err != nil {
		return nil, err
	}
	var out []pkg
	for line := range strings.Lines(string(data)) {
		f := strings.Fields(line)
		if len(f) >= 2 && (f[0] == "pkg" || f[0] == "provider") {
			out = append(out, pkg{rel: f[1], provider: f[0] == "provider"})
		}
	}
	return out, nil
}

func importPath(rel string) string {
	if rel == "chok" {
		return module
	}
	return module + "/" + rel
}

func dirOf(root, rel string) string {
	if rel == "chok" {
		return root
	}
	return filepath.Join(root, filepath.FromSlash(rel))
}

// entry is one go doc -short line.
type entry struct {
	decl        string // the line, indentation removed
	constructor bool   // indented under its type
	about       string
}

var declName = regexp.MustCompile(`^(func|type|var|const) (\w+)`)

// render builds docs/api.md for the checkout at root.
func render(root string) ([]byte, error) {
	pkgs, err := packages(root)
	if err != nil {
		return nil, err
	}
	type section struct {
		p        pkg
		synopsis string
		entries  []entry
	}
	var sections []section
	total := 0
	for _, p := range pkgs {
		cmd := exec.Command("go", "doc", "-short", importPath(p.rel))
		cmd.Dir = root
		out, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go doc -short %s: %w", importPath(p.rel), err)
		}
		dp, err := docPackage(dirOf(root, p.rel), importPath(p.rel))
		if err != nil {
			return nil, err
		}
		s := section{p: p, synopsis: synopsis(dp, dp.Doc)}
		for line := range strings.Lines(string(out)) {
			trimmed := strings.TrimSpace(line)
			m := declName.FindStringSubmatch(trimmed)
			if m == nil {
				continue
			}
			about, err := describe(dp, m[1], m[2])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", p.rel, err)
			}
			s.entries = append(s.entries, entry{decl: trimmed, constructor: trimmed != strings.TrimRight(line, "\n"), about: about})
		}
		total += len(s.entries)
		sections = append(sections, s)
	}

	var b bytes.Buffer
	b.WriteString(`# API map

<!-- Code generated by go run ./internal/tools/apidoc; DO NOT EDIT. -->

The public API of chok v3, package by package: every declaration
` + "`go doc -short`" + ` lists — a constructor under its type (↳), a group of
constants or variables as one line — with the first sentence of its
comment. These are the declarations ` + "`make budget`" + ` counts against
` + "`hack/budget.txt`" + `; methods are not listed, as they are not counted. The
full documentation is on pkg.go.dev and in ` + "`go doc`" + `.

| Package | Declarations |
|---|---|
`)
	for _, s := range sections {
		name := s.p.rel
		if s.p.provider {
			name += " (provider)"
		}
		fmt.Fprintf(&b, "| [`%s`](#%s) | %d |\n", name, anchor(s.p.rel), len(s.entries))
	}
	fmt.Fprintf(&b, "| total | %d |\n", total)
	for _, s := range sections {
		fmt.Fprintf(&b, "\n## %s\n\n`import %q`", s.p.rel, importPath(s.p.rel))
		if s.synopsis != "" {
			fmt.Fprintf(&b, " — %s", cell(s.synopsis))
		}
		b.WriteString("\n\n| Declaration | |\n|---|---|\n")
		for _, e := range s.entries {
			mark := ""
			if e.constructor {
				mark = "↳ "
			}
			fmt.Fprintf(&b, "| %s`%s` | %s |\n", mark, strings.ReplaceAll(e.decl, "|", `\|`), cell(e.about))
		}
	}
	return b.Bytes(), nil
}

// anchor is GitHub's heading anchor for a package heading.
func anchor(rel string) string {
	return strings.ReplaceAll(rel, "/", "")
}

var cellEscaper = strings.NewReplacer("|", `\|`, "*", `\*`, "<", "&lt;", ">", "&gt;")

func cell(s string) string {
	return cellEscaper.Replace(strings.Join(strings.Fields(s), " "))
}

// docPackage reads the package's non-test files with their comments.
func docPackage(dir, path string) (*doc.Package, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	return doc.NewFromFiles(fset, files, path)
}

// describe is the first sentence of the comment of the declaration go doc
// lists as kind name; a group of values is named in full.
func describe(p *doc.Package, kind, name string) (string, error) {
	switch kind {
	case "func":
		for _, f := range p.Funcs {
			if f.Name == name {
				return synopsis(p, f.Doc), nil
			}
		}
		for _, t := range p.Types {
			for _, f := range t.Funcs {
				if f.Name == name {
					return synopsis(p, f.Doc), nil
				}
			}
		}
	case "type":
		for _, t := range p.Types {
			if t.Name == name {
				return synopsis(p, t.Doc), nil
			}
		}
	case "var", "const":
		values := p.Vars
		if kind == "const" {
			values = p.Consts
		}
		for _, t := range p.Types {
			if kind == "const" {
				values = append(values, t.Consts...)
			} else {
				values = append(values, t.Vars...)
			}
		}
		for _, v := range values {
			if len(v.Names) == 0 || v.Names[0] != name {
				continue
			}
			text := v.Doc
			if text == "" {
				if spec, ok := v.Decl.Specs[0].(*ast.ValueSpec); ok && spec.Doc != nil {
					text = spec.Doc.Text()
				}
			}
			about := synopsis(p, text)
			if len(v.Names) > 1 {
				about = strings.Join(v.Names, ", ") + ": " + about
			}
			return about, nil
		}
	}
	return "", fmt.Errorf("go doc lists %s %s, but its declaration was not found", kind, name)
}

// synopsis is the first sentence of text as go/doc cleans it. go/doc
// returns none for a text that starts like a copyright notice — with
// "copyright", "all rights" or "author" — which the comment of an
// Authorize function does, so such a text is read behind a neutral word.
func synopsis(p *doc.Package, text string) string {
	if s := p.Synopsis(text); s != "" || strings.TrimSpace(text) == "" {
		return s
	}
	const lead = "Then "
	return strings.TrimPrefix(p.Synopsis(lead+text), lead)
}
