// code renders a default value.
func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}

func rules(k conf.Key) string {
	var parts []string
	if k.Secret {
		parts = append(parts, "**secret**")
	}
	if k.Rules != "" {
		parts = append(parts, code(k.Rules))
	}
	return strings.Join(parts, " ")
}

// cellEscaper keeps a comment's text literal in a Markdown table cell:
// no column break, no emphasis, no HTML tag such as <endpoint>.
var cellEscaper = strings.NewReplacer("|", `\|`, "*", `\*`, "<", "&lt;", ">", "&gt;")

// cell is a comment as one table cell.
func cell(s string) string {
	return cellEscaper.Replace(strings.Join(strings.Fields(s), " "))
}

// isChokCheckout makes docs gen refuse to run anywhere but in chok's own
// repository.
func isChokCheckout(root string) error {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil || !moduleLine.Match(data) || string(moduleLine.FindSubmatch(data)[1]) != chokModule {
		return fmt.Errorf("docs gen: %s is not a chok checkout (no go.mod of %s); docs gen documents chok itself", root, chokModule)
	}
	return nil
}

// sourceIndex finds the declarations of the configuration types in the
// checkout's source.
type sourceIndex struct {
	root  string
	specs map[string]map[string]*ast.TypeSpec // package path → type name → declaration
}

func (s *sourceIndex) types(pkgPath string) (map[string]*ast.TypeSpec, error) {
	if m, ok := s.specs[pkgPath]; ok {
		return m, nil
	}
	rel, ok := strings.CutPrefix(pkgPath, chokModule)
	if !ok {
		return nil, fmt.Errorf("docs gen: %s is not a package of %s", pkgPath, chokModule)
	}
	dir := filepath.Join(s.root, filepath.FromSlash(strings.TrimPrefix(rel, "/")))
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("docs gen: %w", err)
	}
	m := map[string]*ast.TypeSpec{}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("docs gen: %w", err)
		}
		for _, d := range f.Decls {
			if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
				for _, sp := range gd.Specs {
					ts := sp.(*ast.TypeSpec)
					m[ts.Name.Name] = ts
				}
			}
		}
	}
	s.specs[pkgPath] = m
	return m, nil
}

// fieldDoc is the comment of the field reached from the declaration of
// decl through the Go field names chain. A field without a comment of its
// own shares the nearest comment above it when that comment names it, as
// in "LoginRateWindow and LoginRateLimit throttle ...".
func (s *sourceIndex) fieldDoc(decl reflect.Type, chain []string) (string, error) {
	m, err := s.types(decl.PkgPath())
	if err != nil {
		return "", err
	}
	ts, ok := m[decl.Name()]
	if !ok {
		return "", fmt.Errorf("docs gen: no declaration of %s in %s", decl.Name(), decl.PkgPath())
	}
	expr := ts.Type
	for i, name := range chain {
		st, ok := expr.(*ast.StructType)
		if !ok {
			return "", fmt.Errorf("docs gen: %s.%s is not a struct", decl, strings.Join(chain[:i], "."))
		}
		at := slices.IndexFunc(st.Fields.List, func(f *ast.Field) bool {
			return slices.ContainsFunc(f.Names, func(n *ast.Ident) bool { return n.Name == name })
		})
		if at < 0 {
			return "", fmt.Errorf("docs gen: %s has no field %s", decl, strings.Join(chain[:i+1], "."))
		}
		field := st.Fields.List[at]
		if i == len(chain)-1 {
			if text := commentText(field); text != "" {
				return text, nil
			}
			for j := at - 1; j >= 0; j-- {
				if above := st.Fields.List[j].Doc; above != nil {
					if strings.Contains(above.Text(), name) {
						return above.Text(), nil
					}
					break
				}
			}
			return "", nil
		}
		expr = field.Type
	}
	return "", errors.New("docs gen: empty field chain")
}

func commentText(f *ast.Field) string {
	if f.Doc != nil {
		return f.Doc.Text()
	}
	if f.Comment != nil {
		return f.Comment.Text()
	}
	return ""
}
