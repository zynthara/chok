// configDoc is docs/config.md, relative to the repository root.
const configDoc = "docs/config.md"

// configSections are the configuration types docs gen documents, with the
// section an application conventionally gives each in its Config.
var configSections = []struct {
	name    string // the Go type
	section string // its yaml section, "" for the top level
	typ     reflect.Type
	about   string
}{
	{"chok.Base", "", reflect.TypeFor[chok.Base](), "Embedded without a tag in every application's Config, so its sections `app`, `http` and `log` sit at the top level."},
	{"db.Config", "db", reflect.TypeFor[db.Config](), "The database handle `db.Open` takes."},
	{"identity.Config", "auth", reflect.TypeFor[identity.Config](), "Accounts, tokens, OAuth providers and the audit log; `identity.New` takes it. The provider entries are keyed by name, such as `google`."},
	{"jobs.Config", "jobs", reflect.TypeFor[jobs.Config](), "Periodic jobs and transactional-outbox workers; `jobs.New` takes it."},
	{"telemetry.Config", "telemetry", reflect.TypeFor[telemetry.Config](), "Prometheus metrics, OpenTelemetry traces and the slog bridge to OpenTelemetry logs; `telemetry.New` takes it."},
	{"cache.Config", "cache", reflect.TypeFor[cache.Config](), "The in-memory and Redis cache layers and the circuit breaker in front of Redis; `cache.New` takes it."},
	{"realtime.Config", "realtime", reflect.TypeFor[realtime.Config](), "The hub that pushes events to browsers over WebSocket and server-sent events, its one-time tickets and its Redis backplane; `realtime.New` takes it."},
	{"mail.Config", "mail", reflect.TypeFor[mail.Config](), "Transactional mail through an SMTP relay, into .eml files or into the log; `mail.New` takes it."},
}

func newDocsCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:    "docs",
		Short:  "Generate chok's own documentation (in a chok checkout)",
		Hidden: true,
	}
	var root string
	var check bool
	gen := &cobra.Command{
		Use:   "gen",
		Short: "Write docs/config.md from the configuration types",
		Long: `Write docs/config.md, the configuration reference, from the Config
types of chok and its batteries: every key with its type, default, secret
mark, validate rules and the comment of its field, read from the source
under --root, which must be a chok checkout. --check writes nothing and
fails when the file is not what it would write.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			want, err := configReference(root)
			if err != nil {
				return err
			}
			path := filepath.Join(root, configDoc)
			have, err := os.ReadFile(path)
			if check {
				if err != nil || !bytes.Equal(have, want) {
					return fmt.Errorf("docs gen --check: %s is not current; run chok docs gen", path)
				}
				_, err := fmt.Fprintf(cmd.OutOrStdout(), "%s is current\n", path)
				return err
			}
			if err == nil && bytes.Equal(have, want) {
				_, err := fmt.Fprintf(cmd.OutOrStdout(), "%s is current\n", path)
				return err
			}
			if err := writeFileAtomic(path, want); err != nil {
				return fmt.Errorf("docs gen: %w", err)
			}
			_, err = fmt.Fprintf(cmd.OutOrStdout(), "%s written\n", path)
			return err
		},
	}
	gen.Flags().StringVar(&root, "root", ".", "the chok checkout")
	gen.Flags().BoolVar(&check, "check", false, "fail if the file is not current, writing nothing")
	cmd.AddCommand(gen)
	return cmd
}

// configReference renders docs/config.md from the types and the source
// under root.
func configReference(root string) ([]byte, error) {
	if err := isChokCheckout(root); err != nil {
		return nil, err
	}
	src := &sourceIndex{root: root, specs: map[string]map[string]*ast.TypeSpec{}}
	var b bytes.Buffer
	b.WriteString(configPreamble)
	for _, s := range configSections {
		title := "`" + s.name + "`"
		if s.section != "" {
			title += " — section `" + s.section + "`"
		}
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n", title, s.about)
		b.WriteString("| Key | Type | Default | Rules | Description |\n|---|---|---|---|---|\n")
		for _, k := range conf.Keys(s.typ) {
			doc, err := src.fieldDoc(k.Decl, k.Field)
			if err != nil {
				return nil, err
			}
			path := k.Path
			if s.section != "" {
				path = s.section + "." + path
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", path, k.Type, code(k.Default), rules(k), cell(doc))
		}
	}
	return b.Bytes(), nil
}

